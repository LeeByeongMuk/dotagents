#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd -P)"
BUILD="$REPO_ROOT/tooling/scripts/build.sh"

fail() { echo "test failed: $*" >&2; exit 1; }

[[ -x "$BUILD" ]] || fail "build script is missing or not executable"

outputs=(dist/claude/CLAUDE.md dist/codex/AGENTS.md dist/gemini/GEMINI.md)
for out in "${outputs[@]}"; do
  [[ -f "$REPO_ROOT/$out" ]] || fail "generated file is missing: $out"
  grep -Fq 'Generated by tooling/scripts/build.sh' "$REPO_ROOT/$out" || fail "generated file lacks its provenance header: $out"
done

# The committed output must match what the current sources produce.
"$BUILD" --check >/dev/null || fail "committed dist output is stale; run make build"

# Every rule file must reach every host, so no host silently loses a rule.
for out in "${outputs[@]}"; do
  for rule in "$REPO_ROOT"/agents/rules/*.md; do
    marker="$(sed -n '3p' "$rule")"
    [[ -n "$marker" ]] || fail "rule file has an empty third line: $rule"
    grep -Fq -- "$marker" "$REPO_ROOT/$out" || fail "generated $out is missing $(basename "$rule")"
  done
done

# Precedence and autonomy must arrive before the rest of the rules.
for out in "${outputs[@]}"; do
  workflow_line="$(grep -n '^## Workflow and precedence$' "$REPO_ROOT/$out" | cut -d: -f1)"
  [[ -n "$workflow_line" ]] || fail "generated $out does not carry the workflow rule heading"
  for other in '^## Code changes$' '^## Git safety$' '^## Security and secrets$'; do
    other_line="$(grep -n "$other" "$REPO_ROOT/$out" | cut -d: -f1)"
    [[ -n "$other_line" ]] || fail "generated $out is missing a rule section: $other"
    [[ "$workflow_line" -lt "$other_line" ]] || fail "workflow rules must precede $other in $out"
  done
done

# Rule headings must be demoted so the host file keeps one top-level title.
for out in "${outputs[@]}"; do
  [[ "$(grep -c '^# ' "$REPO_ROOT/$out")" -eq 1 ]] || fail "generated $out must contain exactly one top-level heading"
done

# Adapters stay thin: the generator, not the adapter, carries rule text.
for adapter in agents/adapters/claude/CLAUDE.md agents/adapters/codex/AGENTS.md agents/adapters/gemini/GEMINI.md; do
  for rule in "$REPO_ROOT"/agents/rules/*.md; do
    marker="$(sed -n '3p' "$rule")"
    if grep -Fq -- "$marker" "$REPO_ROOT/$adapter"; then
      fail "rule text was copied into the adapter source: $adapter"
    fi
  done
done

# Staleness must be detected rather than silently accepted.
work="$(mktemp -d "${TMPDIR:-/tmp}/dotagents-build.XXXXXX")"
# dist/ may be the live entry point, so restore it even if the test is cut short.
trap 'if [[ -f "$work/claude.bak" ]]; then cp "$work/claude.bak" "$REPO_ROOT/dist/claude/CLAUDE.md"; fi; rm -rf "$work"' EXIT
cp "$REPO_ROOT/dist/claude/CLAUDE.md" "$work/claude.bak"
printf '\n<!-- drift -->\n' >> "$REPO_ROOT/dist/claude/CLAUDE.md"
if "$BUILD" --check >/dev/null 2>&1; then
  cp "$work/claude.bak" "$REPO_ROOT/dist/claude/CLAUDE.md"
  fail "--check accepted a modified generated file"
fi
cp "$work/claude.bak" "$REPO_ROOT/dist/claude/CLAUDE.md"
"$BUILD" --check >/dev/null || fail "--check failed after restoring the generated file"

# Regeneration is deterministic.
before="$(cat "$REPO_ROOT/dist/claude/CLAUDE.md")"
"$BUILD" >/dev/null
[[ "$before" == "$(cat "$REPO_ROOT/dist/claude/CLAUDE.md")" ]] || fail "build is not deterministic"

# Install must link hosts at the generated output, not the thin source.
for pair in 'claude/CLAUDE.md' 'codex/AGENTS.md' 'gemini/GEMINI.md'; do
  grep -Fq "\$REPO_ROOT/dist/$pair" "$REPO_ROOT/tooling/scripts/install.sh" || fail "install does not link dist/$pair"
done
for pair in 'claude/CLAUDE.md' 'codex/AGENTS.md' 'gemini/GEMINI.md'; do
  if grep -Fq "|\$REPO_ROOT/agents/adapters/$pair\"" "$REPO_ROOT/tooling/scripts/install.sh"; then
    fail "install still links the thin adapter source for $pair"
  fi
done

echo "Host file composition passed."
