#!/usr/bin/env bash
# Composes each host entry point from its thin adapter and the common rules.
# Sources stay in agents/; generated output lands in dist/ and is what install links.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd -P)"
RULES_DIR="$REPO_ROOT/agents/rules"
OUT_ROOT="$REPO_ROOT/dist"
CHECK_ONLY=0

fail() { echo "error: $*" >&2; exit 1; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) CHECK_ONLY=1 ;;
    -h|--help) echo "Usage: $0 [--check]"; exit 0 ;;
    *) fail "unknown argument: $1" ;;
  esac
  shift
done

# host|adapter path relative to agents/adapters|output path relative to dist
hosts=(
  "claude|claude/CLAUDE.md|claude/CLAUDE.md"
  "codex|codex/AGENTS.md|codex/AGENTS.md"
  "gemini|gemini/GEMINI.md|gemini/GEMINI.md"
)

# Rules the model needs before it decides how to act come first. Any rule file
# not listed here is appended in sorted order, so a new file is never dropped.
preferred_order=(workflow.md coding.md git.md documentation.md security.md)

ordered_rules() {
  local seen="" rule
  for rule in "${preferred_order[@]}"; do
    if [[ -f "$RULES_DIR/$rule" ]]; then
      printf '%s\n' "$rule"
      seen="$seen $rule "
    fi
  done
  for rule in "$RULES_DIR"/*.md; do
    [[ -f "$rule" ]] || continue
    rule="$(basename "$rule")"
    [[ "$seen" == *" $rule "* ]] || printf '%s\n' "$rule"
  done
}

render_host() {
  local adapter="$1" rule
  printf '%s\n' "<!-- Generated by tooling/scripts/build.sh from agents/adapters and agents/rules. Edit those sources, then run make build. -->"
  printf '\n'
  cat "$adapter"
  printf '\n'
  printf '%s\n' "---"
  printf '\n'
  printf '%s\n' "이 아래는 공통 규칙 원본을 그대로 합친 것이다. 원본은 \`rules/<파일>\`이며 수정은 원본에서 한다."
  while IFS= read -r rule; do
    printf '\n'
    sed -e 's/^#/##/' "$RULES_DIR/$rule"
  done < <(ordered_rules)
}

status=0
for entry in "${hosts[@]}"; do
  IFS='|' read -r host adapter_rel out_rel <<< "$entry"
  adapter="$REPO_ROOT/agents/adapters/$adapter_rel"
  out="$OUT_ROOT/$out_rel"
  [[ -f "$adapter" ]] || fail "adapter is missing: agents/adapters/$adapter_rel"

  rendered="$(render_host "$adapter")"
  if [[ "$CHECK_ONLY" -eq 1 ]]; then
    if [[ ! -f "$out" ]]; then
      echo "stale: dist/$out_rel is missing" >&2
      status=1
    elif [[ "$rendered" != "$(cat "$out")" ]]; then
      echo "stale: dist/$out_rel does not match its sources" >&2
      status=1
    fi
  else
    mkdir -p "$(dirname "$out")"
    printf '%s\n' "$rendered" > "$out"
    echo "wrote dist/$out_rel"
  fi
done

if [[ "$CHECK_ONLY" -eq 1 ]]; then
  [[ "$status" -eq 0 ]] || fail "generated files are out of date; run make build"
  echo "dist is current"
fi
